test('task editor directly confirms scheduling with focus and fixed execution settings',async({page})=>{
 const errors:string[]=[];page.on('pageerror',e=>errors.push(e.message))
 await page.goto('http://127.0.0.1:1420/#/tasks')
 const opener=page.getByRole('button',{name:'新建任务',exact:true})
 await opener.click()
 const editor=page.getByRole('dialog',{name:'新建任务',exact:true})
 await expect(editor).toBeFocused()
 await page.keyboard.press('Shift+Tab')
 await expect(editor.getByRole('button',{name:'取消',exact:true})).toBeFocused()
 await page.keyboard.press('Tab')
 await expect(editor.getByRole('button',{name:'关闭',exact:true})).toBeFocused()
 await page.evaluate(()=>document.fonts.ready)
 await page.clock.runFor(200)
 await page.screenshot({path:'../docs/screenshots/dialogs/create-task.png',animations:'disabled'})
 await editor.getByRole('option').first().click()
 await editor.getByLabel('任务名称').fill('验证弹窗排程')
 await editor.getByLabel('提示词',{exact:false}).fill('继续检查测试结果，不修改无关文件。')
 await editor.locator('#task-time').fill('2026-10-17T09:30')
 await editor.getByRole('combobox',{name:'重复执行',exact:true}).click();await editor.getByRole('option',{name:'按小时间隔',exact:true}).click()
 await editor.getByRole('spinbutton',{name:'重复间隔小时数'}).fill('8')
 await expect(editor.getByRole('button',{name:'高级设置'})).toHaveCount(0)
 await expect(editor.getByRole('checkbox')).toHaveCount(0)
 await expect(editor.locator('.editor-project,.session-selection-hint')).toHaveCount(0)
 await expect(editor.getByRole('button',{name:'确认创建'})).toBeEnabled()
 await expect(page.getByRole('dialog',{name:'确认排程'})).toHaveCount(0)
 await editor.getByRole('button',{name:'确认创建'}).click()
 await expect(page.getByRole('dialog')).toHaveCount(0)
 const request=await page.evaluate(()=>(window as any).__codebeatCalls.find((c:any)=>c.command==='create_task').args.request)
 expect(request).toMatchObject({title:'验证弹窗排程',permission_profile:'full_access',catch_up_policy:'ask',wake_to_run:true,notify:true,consent:true,recurrence:{kind:'every_hours',hours:8}})
 await expect(page.locator('body')).not.toHaveClass(/dialog-open/)
 expect(errors).toEqual([])
})

test('tool switch clears session without an authorization checkbox, and small-window actions stay accessible',async({page})=>{
 await page.goto('http://127.0.0.1:1420/#/tasks');await page.getByRole('button',{name:'新建任务',exact:true}).click()
 const dialog=page.getByRole('dialog',{name:'新建任务',exact:true})
 await dialog.getByRole('option').first().click()
 await dialog.getByRole('button',{name:'Claude Code',exact:true}).click()
 await expect(dialog.getByRole('checkbox')).toHaveCount(0)
 await expect(dialog.getByRole('listbox').getByRole('option',{selected:true})).toHaveCount(0)
 await expect(dialog.getByRole('button',{name:'确认创建'})).toBeDisabled()
 await page.setViewportSize({width:620,height:640})
 await page.clock.runFor(200)
 await page.screenshot({path:'../docs/screenshots/dialogs/create-task-small.png',animations:'disabled'})
 const button=(await dialog.getByRole('button',{name:'确认创建'}).boundingBox())!
 expect(button.y+button.height).toBeLessThanOrEqual(640)
 expect(await dialog.evaluate(el=>el.scrollWidth<=el.clientWidth)).toBe(true)
 await page.keyboard.press('Escape');await expect(dialog).toHaveCount(0)
 await expect(page.getByRole('button',{name:'新建任务',exact:true})).toBeFocused()
})

