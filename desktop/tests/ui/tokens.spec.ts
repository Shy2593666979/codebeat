test('scheduled quota refresh updates token counters while historical ranges and dark layout work',async({page})=>{
 await page.addInitScript(()=>{const g=window as any,invoke=g.__TAURI_INTERNALS__.invoke;g.__TAURI_INTERNALS__.invoke=async(command:string,args:any)=>{const result=await invoke(command,args);if(command==='get_token_usage'&&g.__extraTokenUsage)result.days.find((day:any)=>day.provider==='codex'&&day.date==='2026-10-16').counts.input+=1000;return result}})
 await page.goto('http://127.0.0.1:1420/#/usage')
 await expect(page.locator('.chart-day')).toHaveCount(30)
 await page.getByRole('combobox',{name:'趋势时间范围',exact:true}).click();await page.getByRole('option',{name:'近 14 天',exact:true}).click()
 await expect(page.locator('.chart-day')).toHaveCount(14)
 const before=await page.evaluate(()=>(window as any).__codebeatCalls.filter((c:any)=>c.command==='get_token_usage').length)
 await page.clock.runFor(31000)
 await page.evaluate(()=>{const g=window as any;g.__extraTokenUsage=true;g.__codebeatEmit('usage-updated',{provider:'codex',report:null,refreshing:false,retrying:false,next_retry_at:null,next_check_at:new Date(Date.now()+600000).toISOString(),last_error:null})})
 await expect.poll(()=>page.evaluate(()=>(window as any).__codebeatCalls.filter((c:any)=>c.command==='get_token_usage').length)).toBeGreaterThan(before)
 await expect(page.getByRole('button',{name:'2026-10-16 Token 明细',exact:true})).toHaveAttribute('data-tokens','29000')
 await expect(page.getByRole('button',{name:'刷新 Token 用量',exact:true})).toHaveCount(0)
 await page.getByRole('combobox',{name:'趋势时间范围',exact:true}).click();await page.getByRole('option',{name:'近 7 天',exact:true}).click()
 await expect(page.locator('.chart-day')).toHaveCount(7)
 await page.evaluate(()=>document.documentElement.dataset.appearance='dark')
 for(const width of [1348,1200,1024,620]){
  await page.setViewportSize({width,height:900})
  const boxes=await page.locator('.token-trend .panel-heading h2,.token-trend .token-controls').evaluateAll(es=>es.map(e=>{const r=e.getBoundingClientRect();return {y:r.y+r.height/2}}))
  expect(Math.abs(boxes[0].y-boxes[1].y)).toBeLessThan(1)
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true)
 }
 await page.screenshot({path:'../docs/screenshots/tokens/usage-dark.png',animations:'disabled'})
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true)
})
