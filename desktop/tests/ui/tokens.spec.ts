import {test,expect} from '@playwright/test'
import path from 'node:path'
import {installDesktopFixture} from './fixtures'
test.use({viewport:{width:1348,height:1024},locale:'zh-CN',timezoneId:'Asia/Shanghai'})
test.beforeEach(async({page})=>{
 await page.route('http://127.0.0.1:1420/**',async route=>{const name=new URL(route.request().url()).pathname,file=path.resolve('dist',name==='/'?'index.html':name.slice(1));if(!file.startsWith(path.resolve('dist')+path.sep)){await route.abort();return}await route.fulfill({path:file})})
 await installDesktopFixture(page)
})
test('rolling week shows token totals, provider filters and clickable daily/period detail',async({page})=>{
 await page.goto('http://127.0.0.1:1420/#/')
 const trend=page.locator('.token-trend')
 await expect(trend.getByRole('button',{name:'2026-10-16 Token 明细',exact:true})).toHaveAttribute('data-tokens','28000')
 await expect(trend.locator('.token-curve-line')).toHaveCount(1)
 await expect(trend.locator('.chart-legend,.chart-bar,.token-summary,.token-source-note')).toHaveCount(0)
 await expect(trend).not.toContainText(/本机日志|输入含缓存|数据说明|点击日期查看明细/)
 await page.screenshot({path:'../docs/screenshots/tokens/home-curve-all.png',animations:'disabled'})
 await expect(trend.locator('.chart-day')).toHaveCount(7)
 await expect(trend).not.toContainText('剩余 %')
 await trend.getByRole('button',{name:'2026-10-16 Token 明细',exact:true}).click()
 const detail=page.getByRole('dialog',{name:'2026-10-16 Token 明细',exact:true})
 await expect(detail.locator('tbody tr')).toHaveCount(2)
 await expect(detail.locator('.token-detail-summary')).toContainText('28,000')
 await expect(detail).toContainText('缓存列仅为其中的明细，不重复相加')
 await page.screenshot({path:'../docs/screenshots/tokens/day-detail.png',animations:'disabled'})
 await detail.getByRole('button',{name:'完成',exact:true}).click()
 await trend.getByRole('combobox',{name:'趋势提供商',exact:true}).click();await page.getByRole('option',{name:'Claude Code',exact:true}).click()
 await expect(trend.getByRole('button',{name:'2026-10-16 Token 明细',exact:true})).toHaveAttribute('data-tokens','14000')
 await expect(trend.locator('.token-curve-line')).toHaveCount(1)
 await trend.getByRole('button',{name:'近 7 天 Token 消耗',exact:true}).click()
 await expect(page.getByRole('dialog').locator('tbody tr')).toHaveCount(7)
 await page.keyboard.press('Escape')
 expect(await page.evaluate(()=>(window as any).__codebeatCalls.some((c:any)=>c.command==='get_token_usage'&&c.args.days===30&&c.args.timezone==='Asia/Shanghai'))).toBe(true)
 await page.screenshot({path:'../docs/screenshots/tokens/home-week.png',animations:'disabled'})
})
