 await page.addInitScript(()=>{const g=window as any,invoke=g.__TAURI_INTERNALS__.invoke;g.__TAURI_INTERNALS__.invoke=(c:string,a:any)=>c==='get_token_usage'?Promise.resolve({days:[],sources:['codex','claude_code'].map(provider=>({provider,status:'missing',files:0,records:0,warnings:[]})),observed_at:new Date().toISOString(),timezone:'Asia/Shanghai'}):invoke(c,a)})
