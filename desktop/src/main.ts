import {createApp} from 'vue'
import {createRouter,createWebHashHistory} from 'vue-router'
import App from './App.vue'
import TrayPanel from './components/TrayPanel.vue'
import NativeNotification from './components/NativeNotification.vue'
import Overview from './pages/Overview.vue'
import Providers from './pages/Providers.vue'
import Schedules from './pages/Schedules.vue'
import History from './pages/History.vue'
import Settings from './pages/Settings.vue'
import Sessions from './pages/Sessions.vue'
import Usage from './pages/Usage.vue'
import './style.css'
import './typography.css'
import './dialogs.css'
import './select-layout.css'
import './task-editor.css'
export const router=createRouter({history:createWebHashHistory(),routes:[{path:'/',component:Overview},{path:'/providers',component:Providers},{path:'/tasks',component:Schedules},{path:'/sessions',component:Sessions},{path:'/usage',component:Usage},{path:'/history',component:History},{path:'/settings',component:Settings},{path:'/optimization',redirect:'/settings'}]})
if(location.hash.split('?')[0]==='#/notification'){document.documentElement.dataset.surface='notification';createApp(NativeNotification).mount('#app')}else if(location.hash.split('?')[0]==='#/tray'){document.documentElement.dataset.surface='tray';createApp(TrayPanel).mount('#app')}else{createApp(App).use(router).mount('#app')}
